import type { MicroStep, Role, RoleId, SkillNode, SkillStatus } from "./types";

function steps(nodeId: string, labels: [string, string, string]): MicroStep[] {
  return labels.map((label, index) => ({ id: `${nodeId}-s${index + 1}`, label }));
}

function skill(
  id: string,
  title: string,
  section: string,
  description: string,
  defaultStatus: SkillStatus,
  prerequisites: string[],
  microSteps: [string, string, string],
  resumeBullet: string,
  linkedinSkill: string,
  course?: SkillNode["course"],
): SkillNode {
  return {
    id,
    title,
    section,
    description,
    defaultStatus,
    prerequisites,
    microSteps: steps(id, microSteps),
    resumeBullet,
    linkedinSkill,
    course,
  };
}

